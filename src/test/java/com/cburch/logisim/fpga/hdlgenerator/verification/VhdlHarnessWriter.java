package com.cburch.logisim.fpga.hdlgenerator.verification;

import com.cburch.logisim.fpga.hdlgenerator.verification.DutInterface.DutPort;
import com.cburch.logisim.fpga.hdlgenerator.verification.DutInterface.Role;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes the VHDL glue between the generic test bench {@code tb_logisim_component} and a generated
 * entity: the package {@code logisim_dut_info} describing the vector layout and the entity {@code
 * logisim_dut_harness} instantiating the generated entity with flattened stimulus and response
 * ports.
 */
final class VhdlHarnessWriter {

  private VhdlHarnessWriter() {}

  static String write(HdlTestCase testCase, DutInterface dut) {
    final var out = new StringBuilder();
    out.append("-- Test harness for ").append(testCase.getDescription()).append('\n')
        .append("-- Generated by the Logisim-evolution HDL verification suite; do not edit.\n\n");
    writePackage(out, testCase, dut);
    out.append('\n');
    writeHarness(out, dut);
    return out.toString();
  }

  private static void writePackage(StringBuilder out, HdlTestCase testCase, DutInterface dut) {
    out.append(
        """
        library ieee;
        use ieee.std_logic_1164.all;

        package logisim_dut_info is
          constant dut_description : string   := %s;
          constant stimulus_bits   : positive := %d;
          constant response_bits   : positive := %d;

          -- Return the vectors split into the ports of the generated entity.
          function describe_stimulus(value : std_logic_vector) return string;
          function describe_response(value : std_logic_vector) return string;
        end package logisim_dut_info;

        package body logisim_dut_info is

          function field(value : std_logic_vector) return string is
          begin
            if value'length > 8 then
              return "0x" & to_hstring(value);
            end if;
            return to_string(value);
          end function field;

        """
            .formatted(
                stringLiteral(testCase.getDescription()),
                dut.getStimulusBits(),
                dut.getResponseBits()));
    writeDescribeFunction(
        out, "describe_stimulus", dut.getPorts(Role.STIMULUS), dut.getPorts(Role.TIED));
    out.append('\n');
    writeDescribeFunction(out, "describe_response", dut.getPorts(Role.RESPONSE), List.of());
    out.append("\nend package body logisim_dut_info;\n");
  }

  private static void writeDescribeFunction(
      StringBuilder out, String name, List<DutPort> ports, List<DutPort> tiedPorts) {
    final var parts = new ArrayList<String>();
    for (final var port : ports) {
      parts.add(
          String.format(
              "\"%s=\" & field(v(%d downto %d))", port.name(), port.msb(), port.offset()));
    }
    for (final var port : tiedPorts) {
      parts.add(String.format("\"%s=%s (tied off)\"", port.name(), port.tieOffBits()));
    }
    out.append("  function ").append(name).append("(value : std_logic_vector) return string is\n")
        .append("    constant v : std_logic_vector(value'length - 1 downto 0) := value;\n")
        .append("  begin\n")
        .append("    return ").append(String.join(" & \", \"\n         & ", parts)).append(";\n")
        .append("  end function ").append(name).append(";\n");
  }

  private static void writeHarness(StringBuilder out, DutInterface dut) {
    out.append("""
        library ieee;
        use ieee.std_logic_1164.all;

        use work.logisim_dut_info.all;

        entity logisim_dut_harness is
          port ( stimulus : in  std_logic_vector(stimulus_bits - 1 downto 0);
                 response : out std_logic_vector(response_bits - 1 downto 0) );
        end entity logisim_dut_harness;

        architecture structure of logisim_dut_harness is
        begin

        """);
    out.append("  dut : entity work.").append(dut.getEntityName()).append('\n');
    final var parameters = dut.getParameters();
    if (!parameters.isEmpty()) {
      out.append("    generic map ( ")
          .append(associations(parameters, "                  "))
          .append(" )\n");
    }
    final var portMap = new LinkedHashMap<String, String>();
    for (final var port : dut.getPorts()) portMap.put(port.name(), actual(port));
    out.append("    port map ( ").append(associations(portMap, "               ")).append(" );\n")
        .append("\nend architecture structure;\n");
  }

  private static String actual(DutPort port) {
    final var vector = port.role() == Role.RESPONSE ? "response" : "stimulus";
    if (port.role() == Role.TIED) {
      return port.scalar() ? "'" + port.tieOffBits() + "'" : "\"" + port.tieOffBits() + "\"";
    }
    return port.scalar()
        ? String.format("%s(%d)", vector, port.offset())
        : String.format("%s(%d downto %d)", vector, port.msb(), port.offset());
  }

  private static String associations(Map<String, String> map, String indent) {
    final var width = map.keySet().stream().mapToInt(String::length).max().orElse(0);
    final var lines = new ArrayList<String>();
    for (final var entry : map.entrySet()) {
      lines.add(String.format("%-" + width + "s => %s", entry.getKey(), entry.getValue()));
    }
    return String.join(",\n" + indent, lines);
  }

  private static String stringLiteral(String text) {
    return "\"" + text.replace("\"", "\"\"") + "\"";
  }
}
