package com.cburch.logisim.fpga.hdlgenerator.verification;

import com.cburch.logisim.fpga.hdlgenerator.verification.DutInterface.DutPort;
import com.cburch.logisim.fpga.hdlgenerator.verification.DutInterface.Role;
import java.util.ArrayList;
import java.util.List;

/**
 * Writes the Verilog module {@code logisim_dut_harness}, which instantiates a generated module
 * with flattened stimulus and response ports for the generic test bench {@code
 * tb_logisim_component}, and provides the task {@code describe} used to report mismatches.
 */
final class VerilogHarnessWriter {

  private VerilogHarnessWriter() {}

  static String write(HdlTestCase testCase, DutInterface dut) {
    final var stimulusRange = range(dut.getStimulusBits());
    final var responseRange = range(dut.getResponseBits());
    final var out = new StringBuilder();
    out.append("// Test harness for ").append(testCase.getDescription()).append('\n')
        .append("// Generated by the Logisim-evolution HDL verification suite; do not edit.\n\n")
        .append("module logisim_dut_harness( stimulus, response );\n")
        .append("  input  ").append(stimulusRange).append(" stimulus;\n")
        .append("  output ").append(responseRange).append(" response;\n\n")
        .append("  ").append(dut.getEntityName());
    final var parameters = new ArrayList<String>();
    dut.getParameters().forEach((name, value) -> parameters.add("." + name + "(" + value + ")"));
    if (!parameters.isEmpty()) {
      out.append(" #( ").append(String.join(",\n      ", parameters)).append(" )");
    }
    final var connections = new ArrayList<String>();
    for (final var port : dut.getPorts()) connections.add("." + port.name() + "(" + actual(port) + ")");
    out.append("\n    dut ( ").append(String.join(",\n          ", connections)).append(" );\n\n");

    out.append("  // Prints a vector split into the ports of the generated module.\n")
        .append("  task describe;\n")
        .append("    input ").append(stimulusRange).append(" value_stimulus;\n")
        .append("    input ").append(responseRange).append(" value_expected;\n")
        .append("    input ").append(responseRange).append(" value_actual;\n")
        .append("    begin\n");
    final var tied = new ArrayList<String>();
    for (final var port : dut.getPorts(Role.TIED)) {
      tied.add(port.name() + "=" + port.tieOffBits() + " (tied off)");
    }
    writeDisplay(out, "inputs  ", dut.getPorts(Role.STIMULUS), "value_stimulus", tied);
    writeDisplay(out, "expected", dut.getPorts(Role.RESPONSE), "value_expected", List.of());
    writeDisplay(out, "actual  ", dut.getPorts(Role.RESPONSE), "value_actual", List.of());
    out.append("    end\n")
        .append("  endtask\n\n")
        .append("endmodule\n");
    return out.toString();
  }

  private static void writeDisplay(
      StringBuilder out, String label, List<DutPort> ports, String vector, List<String> extra) {
    final var format = new ArrayList<String>();
    final var arguments = new ArrayList<String>();
    for (final var port : ports) {
      format.add(port.name() + (port.width() > 8 ? "=0x%h" : "=%b"));
      arguments.add(String.format("%s[%d:%d]", vector, port.msb(), port.offset()));
    }
    format.addAll(extra);
    out.append("      $display(\"  ").append(label).append(": ").append(String.join(", ", format))
        .append("\", ").append(String.join(", ", arguments)).append(");\n");
  }

  private static String actual(DutPort port) {
    if (port.role() == Role.TIED) return port.width() + "'b" + port.tieOffBits();
    final var vector = port.role() == Role.RESPONSE ? "response" : "stimulus";
    return port.scalar()
        ? String.format("%s[%d]", vector, port.offset())
        : String.format("%s[%d:%d]", vector, port.msb(), port.offset());
  }

  private static String range(int bits) {
    return "[" + (bits - 1) + ":0]";
  }
}
